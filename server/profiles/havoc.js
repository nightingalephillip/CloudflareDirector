import { requireHop1 } from './common.js';

// Havoc .yaotl profile — Listener block pointing at hop 1.
// Structure follows the reference redirector's demo-profile.yaotl.
export function build(chain, settings, options = {}) {
  const h = requireHop1(chain, settings, options);
  const killdate = options.killdate ? `KillDate: "${options.killdate}"` : '';
  const content = `# Havoc profile generated by cloudflaredirector
# Chain "${chain.name}" — implant traffic only ever touches hop 1.

Teamserver {
    Host = "127.0.0.1"
    Port = 40056

    Build {
        Compiler64 = "data/x86_64-w64-mingw32-cross/bin/x86_64-w64-mingw32-gcc"
        Compiler86 = "data/i686-w64-mingw32-cross/bin/i686-w64-mingw32-gcc"
        Nasm = "/usr/bin/nasm"
    }
}

Operators {
    User "pentester" {
        Password = "changeme"
    }
}

Listeners {
    Http {
        Name: "Redirector-HTTP"
        Response: {
            Headers: [
                "Content-Type: text/html"
            ]
        }
        Hosts: [
            "${h.host}"
        ]
        HostBind: "0.0.0.0"
        HostRotation: "round-robin"
        PortBind: 443
        PortConn: 443
        Secure: true
        ${killdate}
        UserAgent: "${h.userAgent}"
        Uris: [
            "/assets/", "/blog/", "/static/", "/api/"
        ]
        Headers: [
            "${h.secretHeader}: ${h.secretValue}"
        ]
    }
}

Demon {
    Sleep: 2
    Jitter: 20
    TrustXForwardedFor: ${chain.c2?.keepXFF ? 'true' : 'false'}

    Injection {
        Spawn64: "C:\\\\Windows\\\\System32\\\\Werfault.exe"
        Spawn32: "C:\\\\Windows\\\\SysWOW64\\\\Werfault.exe"
    }
}
`;

  return {
    framework: 'havoc',
    filename: `${chain.name}-havoc.yaotl`,
    language: 'yaml',
    content,
    commands: [`havoc client --profile ${chain.name}-havoc.yaotl`],
    notes: [
      'Hosts lists only hop 1 — that is the only implant-facing endpoint.',
      'Adjust Teamserver/Operators for your teamserver before loading.',
    ],
  };
}
